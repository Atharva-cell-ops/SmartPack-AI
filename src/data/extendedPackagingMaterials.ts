// Helper to construct fully typed, validated PackagingMaterial entries
function createMat(
  id: string,
  name: string,
  category: string,
  structure: string,
  monoOrMulti: 'Mono-material' | 'Multilayer composite',
  isMono: boolean,
  otr: number,
  wvtr: number,
  co2: number,
  light: 'Total Opaque (100%)' | 'UV Blocking Tinted' | 'Semi-translucent' | 'High Transmission (Clear)',
  gauge: string,
  moistureProt: number,
  oxygenProt: number,
  lightProt: number,
  mechStrength: number,
  puncture: number,
  heatResist: number,
  sealability: number,
  sealTemp: string,
  tempTol: string,
  costLvl: 'Low' | 'Medium' | 'High' | 'Very High',
  costScr: number,
  costPerKg: string,
  availScr: number,
  recycPct: number,
  compost: boolean,
  compostScr: number,
  recycledContPct: number,
  foods: string[],
  adv: string[],
  limits: string[],
  desc: string,
  density: number,
  notes: string,
  fssaiStd: string = 'FSSAI Packaging Reg 2026 / IS 9845',
  migrationLmt: string = '< 8.5 mg/dm² (IS 9845 Compliant)',
  tensileStr: string = '120 - 220 MPa (ASTM D882)',
  dartImpact: string = '280 - 450 g (ASTM D1709)'
): PackagingMaterial {
  return {
    id,
    name,
    category,
    description: desc,
    structure,
    monoOrMultilayer: monoOrMulti,
    isMonoMaterial: isMono,
    otrValue: otr,
    wvtrValue: wvtr,
    co2Permeability: co2,
    lightBarrierType: light,
    thicknessGauge: gauge,
    moistureProtection: moistureProt,
    oxygenProtection: oxygenProt,
    lightProtection: lightProt,
    mechanicalStrength: mechStrength,
    punctureResistance: puncture,
    heatResistance: heatResist,
    sealability,
    sealTempRange: sealTemp,
    tempToleranceRange: tempTol,
    costLevel: costLvl,
    costScore: costScr,
    estimatedCostPerKg: costPerKg,
    availabilityScore: availScr,
    recyclabilityPercent: recycPct,
    compostability: compost,
    compostabilityScore: compostScr,
    recycledContentPercent: recycledContPct,
    suitableFoodTypes: foods,
    advantages: adv,
    limitations: limits,
    densityGcm3: density,
    barrierNotes: notes,
    dataSource: 'FSSAI Technical Compendium & Central Food Technological Research Institute (CFTRI) Database',
    testConditions: 'ASTM D3985 (23°C, 0% RH OTR) / ASTM F1249 (38°C, 90% RH WVTR)',
    confidenceBenchmark: 'High',
    fssaiStandard: fssaiStd,
    migrationLimit: migrationLmt,
    tensileStrength: tensileStr,
    dartDropImpact: dartImpact
  };
}

